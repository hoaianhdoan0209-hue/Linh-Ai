import assert from 'node:assert/strict';
import {buildEvidence} from './gateway/game-context.mjs';
import {assessAnswer} from './gateway/answer-audit.mjs';
const k=buildEvidence('Karmic Cinderpult');
let output=assessAnswer('Karmic Cinderpult giúp sát thương Adhesive Gunpowder 480% khi mục tiêu đủ trạng thái.',k);
assert.equal(output.accepted,true,JSON.stringify(output));
output=assessAnswer('Karmic Cinderpult tăng toàn bộ sát thương 480%, cứ xây full DPS.',k);
assert.equal(output.accepted,false);
assert.ok(output.flags.includes('skill-only-effect-generalized'));
assert.match(output.reply,/Adhesive Gunpowder/);
assert.doesNotMatch(output.reply,/toàn bộ sát thương 480%/);
output=assessAnswer('Karmic Cinderpult tăng 98765% damage.',k);
assert.equal(output.accepted,false);
assert.ok(output.flags.includes('percentage-not-in-retrieved-patch'));
assert.ok(!output.reply.includes('98765%'));
output=assessAnswer('Build này chắc chắn mạnh nhất.',k);
assert.equal(output.accepted,false);
assert.ok(output.flags.includes('unsupported-certainty'));
output=assessAnswer('Chỉ kiểm tra điều kiện cokerize trước. Không có phép đo.',k);
assert.equal(output.accepted,true);
output=assessAnswer('Hôm nay trời đẹp, 98765% niềm vui.',buildEvidence('Xin chào'));
assert.equal(output.accepted,true,'Normal social dialogue must not get game-only audit');
assert.equal(assessAnswer('Không có số đo.',buildEvidence('Multishot')).accepted,true);
assert.equal(assessAnswer('Một chỉ số +50% không được công bố.',buildEvidence('Multishot')).accepted,false);
console.log('PASS: post-model SS9 gate rejects invented percentages, exaggerated effects and unmeasured certainty');
