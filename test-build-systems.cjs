'use strict';
const assert=require('node:assert/strict');
const B=require('./build-systems.js');
assert.equal(B.RELEASE,'SS9');
assert.equal(B.systems.length,11);
assert.ok(B.official.transition.includes('/344'));
assert.equal(B.assess('hello'),null);
assert.equal(B.inspect('unrelated text'),null);
const t=B.inspect('Tarta 3 món Hellscream',{source:'image'});
assert.equal(t.pieceCount,3);
assert.equal(t.source,'unconfirmed-ocr');
assert.equal(t.verified,false);
assert.deepEqual(t.mechanicIds,['tarta']);
const before=B.assess('nên dùng không?',{context:t});
assert.match(before.text,/3\/4 món/);
assert.match(before.text,/KHÔNG/);
assert.equal(before.confidence,'needs-build-evidence');
const full=B.assess('Tarta 4 món');
assert.match(full.text,/4\/4 món/);
assert.match(full.text,/Earthspike/);
assert.doesNotMatch(full.text,/KHÔNG được lấy hệ số/);
const c=B.assess('Karmic Cinderpult có tăng cả build không?');
assert.match(c.text,/Adhesive Gunpowder/);
assert.match(c.text,/cokerize/);
assert.doesNotMatch(c.text,/mọi đòn đều \+480%/);
const wind=B.assess('Anemoian Cortain build');
assert.match(wind.text,/airburst/);
assert.match(wind.text,/Fortitude/);
const names=B.assess('Charred Aperture tương tác thế nào');
assert.match(names.text,/Iridescence/);
const generic=B.assess('nên tối ưu build ra sao?');
assert.match(generic.text,/Không thể xếp hạng build/);
assert.match(generic.text,/Specialization/);
assert.match(generic.text,/Fatestone/);
assert.ok(generic.missing.some(x=>x.includes('Eidolon')),'Eidolon must remain a tracked dependency even when not in top three questions');
const old=B.assess('fatebound nào mạnh nhất');
assert.match(old.text,/SS8 chuyển sang Fatestone/);
const forge=B.assess('Forged và Celesturgic affix nên chọn gì?');
assert.match(forge.text,/khác nhau/);
assert.equal(B.inspect('Mật khẩu riêng: 123'),null);
assert.ok(B.assess('Karmic Cinderpult').text.length<=800);
// The same build can accumulate explicitly mentioned layers across turns,
// but casual chat or an unrelated question should never be hijacked.
let state=B.inspect('Tôi chơi Wildwalker với Breath of the Wild',{source:'user-text'});
assert.ok(state.systemIds.includes('class'));
assert.ok(state.systemIds.includes('skills'));
state=B.merge(state,B.inspect('Anemoian Cortain',{source:'user-text'}));
const deep=B.assess('nên dùng không?',{context:state});
assert.match(deep.text,/Fortitude/);
assert.ok(!deep.missing.some(x=>x.includes('lớp nhân vật')));
assert.equal(B.assess('Cảm ơn',{context:state}),null);
assert.equal(B.assess('xóa hội thoại',{context:state}),null);
assert.equal(B.merge(state,null).season,'SS9');
console.log('PASS: 11 SS9 build systems, gated triggers, source-aware OCR and no imaginary global DPS');
