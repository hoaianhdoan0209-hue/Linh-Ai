const assert=require('node:assert/strict');
const V=require('./vision-engine.js'),M=require('./web-image-memory.js'),C=require('./game-coach.js');
const raw='Sát thương đòn thường: 1000\nCông kích: 1.500\nTỷ lệ chí mạng: 30%\nSát thương chí mạng: 200%\nTốc độ đánh: 2 đòn/s\nHồi chiêu: 8 giây\nThời lượng: 5 giây';
const item=M.candidate(raw,V.observe(raw));
assert.equal(item.facts.find(f=>f.key==='attackPower').value,1500);
assert.equal(item.facts.find(f=>f.key==='baseDamage').value,1000);
assert.equal(item.facts.find(f=>f.key==='attackSpeed').value,2);
const coach=C.create();
assert.match(coach.image(item).text,/OCR chưa xác nhận/);
let answer=coach.reply('tổng');
assert.match(answer.text,/1,3×/);
assert.match(answer.text,/1\.300/);
assert.match(answer.text,/2\.600/);
assert.match(answer.text,/62,5%/);
answer=coach.reply('gợi ý tối ưu đánh boss');
assert.match(answer.text,/7,69%/);
assert.match(answer.text,/2,31%/);
assert.match(answer.text,/ưu tiên tỷ lệ/);
assert.match(coach.reply('tỷ lệ chí mạng: 40%').text,/1,4×/);
assert.match(coach.reply('DPS bao nhiêu').text,/2\.800/);
assert.match(coach.reply('so sánh').text,/30 → 40/);
assert.match(coach.reply('vậy tăng chí mạng lên 50%').text,/1,5×/);
assert.match(coach.reply('tăng chí mạng thêm 5%').text,/1,55×/);
const newPic=M.candidate('Công kích: 300',V.observe('Công kích: 300'));
coach.image(newPic);
assert.doesNotMatch(coach.reply('tính dps').text,/2\.800|1,4×/,'Never splice unrelated pictures');
assert.match(coach.reply('1000 * 1,3').text,/1\.300/);
assert.match(coach.reply('10 / 0').text,/chia cho 0/);
assert.equal(coach.reply('chào Socrates'),null);
assert.equal(coach.reply('ghi nhớ: boss có giáp'),null);
assert.equal(coach.reply('Karmic Cinderpult sát thương'),null);
assert.equal(V.observe('Attack speed: 30%').facts.some(f=>f.key==='attackSpeed'),false);
assert.equal(V.observe('Cooldown: 20%').facts.some(f=>f.key==='cooldown'),false);
assert.equal(V.observe('Attack: 100%').facts.some(f=>f.key==='attackPower'),false);
assert.equal(M.candidate('HP',V.observe('HP: 50000')).facts[0].value,50000);
const saved=M.approve([],item).items;
assert.doesNotMatch(JSON.stringify(saved),/Sát thương đòn thường|Công kích|base64|source/);
assert.match(C.create().reply('phân tích ảnh',saved).text,/1\.000/);
const fs=require('node:fs'),html=fs.readFileSync('index.html','utf8');
assert.ok(html.includes('const analysis=coach.image(pendingImage)'));
assert.ok(html.includes('coach.reply(message,lastPatch?[]:savedImages)'));
// Two screenshot alternatives must remain separate and yield a conditional choice.
const alphaRaw='Sát thương đòn thường: 1000\nTỷ lệ chí mạng: 30%\nSát thương chí mạng: 200%\nTốc độ đánh: 2 đòn/s';
const betaRaw='Sát thương đòn thường: 1100\nTỷ lệ chí mạng: 40%\nSát thương chí mạng: 200%\nTốc độ đánh: 2 đòn/s';
const comparison=C.create();
comparison.image(M.candidate(alphaRaw,V.observe(alphaRaw)));
const immediate=comparison.image(M.candidate(betaRaw,V.observe(betaRaw)));
assert.match(immediate.text,/So sánh riêng hai ảnh/);
assert.match(immediate.text,/30 → 40/);
assert.match(immediate.text,/Chưa đủ dữ kiện đồng nhất/);
const afterCrit=comparison.reply('tổng');
assert.match(afterCrit.text,/DPS giả định/,'Crit interpretation must immediately recalculate comparison');
assert.match(comparison.reply('boss').text,/Đánh boss/);
assert.match(comparison.reply('farm').text,/Đánh farm|Đánh boss|Đánh farm cần thêm|Đánh farm cần|Đánh farm|Đánh farm/i);
const choice=comparison.reply('nên chọn món nào');
assert.match(choice.text,/DPS giả định/);
assert.match(choice.text,/2\.600/);
assert.match(choice.text,/3\.080/);
assert.match(choice.text,/phương án B cho giá trị lớn hơn/);
assert.match(choice.text,/CHƯA thể chọn món đó cho cả build/);
assert.match(choice.text,/Fatestone/);
assert.match(choice.text,/Mất một tương tác có thể đảo kết quả/);
