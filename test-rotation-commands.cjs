'use strict';
const assert=require('node:assert/strict');
const P=require('./rotation-commands.js');
assert.equal(P.parse('Xin chào'),null);
assert.match(P.parse('Mô phỏng').error,/thời lượng/);
const basic='mô phỏng 6s; skill shot damage 100 cooldown 2s';
let parsed=P.parse(basic);
assert.ok(parsed.model);
assert.equal(parsed.model.duration,6);
assert.equal(parsed.model.skills[0].cooldown,2);
let a=P.answer(basic);
assert.match(a.text,/400 sát thương/);
assert.match(a.text,/shot 4/);
assert.match(a.text,/kháng/);
const combo='mô phỏng 5s; skill scorch damage 0 cooldown 5s status cokerize 3s; skill adhesive damage 100 cooldown 2s; effect karmic skill adhesive factor 5,8 assumed if cokerize';
parsed=P.parse(combo);
assert.equal(parsed.model.effects[0].factor,5.8);
assert.equal(parsed.model.skills[0].hits[0].status,'cokerize');
a=P.answer(combo);
assert.match(a.text,/1\.260/);
assert.match(a.text,/2 hit/);
assert.match(a.text,/giả định/);
assert.match(P.parse(combo+'; effect other skill noexist factor 2 assumed').error,/Hiệu ứng/);
assert.match(P.parse('mô phỏng 20s; không hiểu cú pháp').error,/Dòng chưa đúng cú pháp/);
assert.ok(P.answer(combo).text.length<=1300);
const resourceCommand='mô phỏng 4s; resource 0/10 regen 5/s; global cooldown 0,5s; skill shot damage 100 cooldown 1s cost 10';
const checked=P.parse(resourceCommand);
assert.equal(checked.model.resource.initial,0);
assert.equal(checked.model.resource.regen,5);
assert.equal(checked.model.globalCooldown,0.5);
assert.match(P.answer(resourceCommand).text,/200 sát thương/);
assert.match(P.parse('mô phỏng 4s; skill shot damage 100 cooldown 1s cost 10').error,/tài nguyên/);
assert.match(P.parse('mô phỏng 5s; resource 10/10 regen 1/s; resource 10/10 regen 1/s; skill a damage 10 cooldown 1s').error,/một nguồn/);
assert.equal(P.parse('mô phỏng 4s; target mob; skill shot damage 100 cooldown 1s').model.targetType,'mob');
console.log('PASS: explicit local multi-skill rotation text syntax, resource/status/conditional experiments');
